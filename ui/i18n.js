  const textRecords = new WeakMap();
  const attributeRecords = new WeakMap();
  let applying = false;
  let scheduled = false;
  let language = readLanguage();

  function readLanguage() {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (SUPPORTED.has(stored)) return stored;
    } catch (_) {}
    return "ru";
  }

  function translateBody(source) {
    if (language !== "en" || !source) return source;
    if (Object.prototype.hasOwnProperty.call(EN, source)) return EN[source];
    for (const [pattern, render] of PATTERNS) {
      const match = source.match(pattern);
      if (match) return render(...match);
    }
    let translated = source;
    for (const [from, to] of FRAGMENTS) translated = translated.replaceAll(from, to);
    return translated;
  }

  function translateValue(source) {
    const match = String(source ?? "").match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!match) return source;
    return `${match[1]}${translateBody(match[2])}${match[3]}`;
  }

  function processText(node) {
    const current = node.nodeValue || "";
    let record = textRecords.get(node);
    if (!record || current !== record.rendered) record = { source: current, rendered: current };
    const rendered = language === "ru" ? record.source : translateValue(record.source);
    record.rendered = rendered;
    textRecords.set(node, record);
    if (current !== rendered) node.nodeValue = rendered;
  }

  function processAttribute(element, name) {
    if (!element.hasAttribute(name)) return;
    const current = element.getAttribute(name) || "";
    let records = attributeRecords.get(element);
    if (!records) {
      records = new Map();
      attributeRecords.set(element, records);
    }
    let record = records.get(name);
    if (!record || current !== record.rendered) record = { source: current, rendered: current };
    const rendered = language === "ru" ? record.source : translateValue(record.source);
    record.rendered = rendered;
    records.set(name, record);
    if (current !== rendered) element.setAttribute(name, rendered);
  }

  function translateTree(root = document.body) {
    if (!root) return;
    applying = true;
    try {
      if (root.nodeType === Node.TEXT_NODE) processText(root);
      const textWalker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
          const parent = node.parentElement;
          return parent && !parent.closest("script,style,code,pre") ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
        }
      });
      while (textWalker.nextNode()) processText(textWalker.currentNode);

      const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
      for (const element of elements) {
        for (const name of ["placeholder", "title", "aria-label", "alt"]) processAttribute(element, name);
      }
    } finally {
      applying = false;
    }
  }

  function updateControls() {
    document.documentElement.lang = language;
    document.querySelectorAll("[data-language]").forEach((button) => {
      const active = button.dataset.language === language;
      button.classList.toggle("active", active);
      if (button.getAttribute("aria-pressed") !== String(active)) button.setAttribute("aria-pressed", String(active));
    });
  }

  function refresh() {
    translateTree(document.body);
    updateControls();
  }

  function setLanguage(next) {
    if (!SUPPORTED.has(next) || next === language) return;
    language = next;
    try { localStorage.setItem(STORAGE_KEY, language); } catch (_) {}
    refresh();
    window.dispatchEvent(new CustomEvent("cgs:language-changed", { detail: { language, locale: locale() } }));
  }

  function locale() {
    return language === "en" ? "en-US" : "ru-RU";
  }

  function scheduleRefresh() {
    if (applying || scheduled) return;
    scheduled = true;
    queueMicrotask(() => {
      scheduled = false;
      refresh();
    });
  }

  const observer = new MutationObserver(scheduleRefresh);
  observer.observe(document.documentElement, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "title", "aria-label", "alt"]
  });

  document.addEventListener("click", (event) => {
    const button = event.target.closest("[data-language]");
    if (button) setLanguage(button.dataset.language);
  });

  window.cgsI18n = {
    get language() { return language; },
    locale,
    setLanguage,
    refresh,
    t(value) { return language === "en" ? translateValue(value) : String(value ?? ""); }
  };

  refresh();
